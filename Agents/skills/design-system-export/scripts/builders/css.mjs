// Stylesheets shared by every target that ships code.
//
//   fonts.css       web-font loading
//   tokens.css      every token, default color modes + responsive modes
//   tokens-contrast.css   optional color modes (medium / high contrast)
//   extras.css      kit sheets passed through as-is (brand palette)
//   base.css        the kit's global sheet, in `@layer base`
//   typography.css  one `.type-<role>` class per typescale role
//   components.css  each shipped component's styles, in `@layer components`
//   theme.css       Tailwind v4 + shadcn/ui mapping (Tailwind projects only)
//
// base and components sit in cascade layers so they never outrank the
// consumer's utilities: unlayered CSS beats every layer, which would otherwise
// let the kit's `h1` rule override a Tailwind `text-sm` on the same element.
import { indent } from "../lib/css.mjs";

const banner = (model, what) =>
  `/*\n * ${model.name} design system — ${what}\n * GENERATED by the design-system-export skill. Do not edit by hand.\n */\n`;

export function fontsCss(model) {
  const google = model.fonts.filter((f) => f.google);
  const families = google
    .map(
      (f) =>
        `family=${f.family.replace(/ /g, "+")}:wght@${f.weights.join(";")}`,
    )
    .join("&");
  const lines = [banner(model, "web fonts").trimEnd()];
  if (google.length)
    lines.push(
      `@import url("https://fonts.googleapis.com/css2?${families}&display=swap");`,
    );
  for (const f of model.fonts.filter((f) => !f.google))
    lines.push(`/* ${f.family} is not on Google Fonts: load it yourself. */`);
  return lines.join("\n") + "\n";
}

export function googleFontsUrl(model) {
  return /url\("([^"]+)"\)/.exec(fontsCss(model))?.[1] ?? null;
}

function tokenBlocks(model, wantOptional) {
  const blocks = [];
  let current = null;
  for (const decl of model.sheets.tokenDeclarations) {
    let selector = decl.selector;
    let label = null;
    if (!decl.media) {
      const mode = model.colorModes.find((m) => m.selector === decl.selector);
      if (Boolean(mode?.optional) !== wantOptional) continue;
      if (mode) {
        selector = mode.exportSelector ?? mode.selector;
        label = mode.label;
      }
    } else {
      if (wantOptional) continue;
      label = model.windowModes.find((m) => m.media === decl.media)?.label;
    }
    if (!current || current.selector !== selector || current.media !== decl.media) {
      current = { selector, media: decl.media, label, lines: [] };
      blocks.push(current);
    }
    current.lines.push(`  ${decl.name}: ${decl.value};`);
  }
  return blocks
    .map((b) => {
      const rule = `${b.selector.replace(/, /g, ",\n")} {\n${b.lines.join("\n")}\n}`;
      const body = b.media ? `@media ${b.media} {\n${indent(rule)}\n}` : rule;
      return b.label ? `/* ${b.label} */\n${body}` : body;
    })
    .join("\n\n");
}

export function tokensCss(model) {
  return `${banner(model, "design tokens")}\n${tokenBlocks(model, false)}\n`;
}

export function tokensContrastCss(model) {
  const body = tokenBlocks(model, true);
  return body
    ? `${banner(model, "optional contrast modes (import after tokens.css)")}\n${body}\n`
    : null;
}

export function extrasCss(model) {
  return model.sheets.extras
    ? `${banner(model, "kit extras")}\n${model.sheets.extras}\n`
    : null;
}

export function baseCss(model) {
  return `${banner(model, "base layer")}\n@layer base {\n${indent(model.sheets.base)}\n}\n`;
}

const TYPE_DECLARATIONS = [
  ["fontFamily", "font-family"],
  ["fontSize", "font-size"],
  ["fontWeight", "font-weight"],
  ["lineHeight", "line-height"],
  ["letterSpacing", "letter-spacing"],
];

export function typographyCss(model) {
  const rules = model.typography
    // The kit's base sheet may already define some of these by hand.
    .filter((role) => !new RegExp(`\\.type-${role.id}\\b`).test(model.sheets.base))
    .map((role) => {
      const decls = TYPE_DECLARATIONS.filter(([prop]) => role.vars[prop]).map(
        ([prop, css]) => `  ${css}: var(${role.vars[prop]});`,
      );
      return `.type-${role.id} {\n${decls.join("\n")}\n}`;
    });
  return `${banner(model, "type role classes")}\n@layer base {\n${indent(rules.join("\n\n"))}\n}\n`;
}

export function componentCss(model, component) {
  return `${banner(model, `${component.name} styles (from ${component.source})`)}\n@layer components {\n${indent(component.css)}\n}\n`;
}

export function componentsCss(model) {
  return model.components.map((c) => componentCss(model, c)).join("\n");
}

/** Tailwind v4 `@theme` + shadcn/ui variables, all aliasing the tokens. */
export function themeCss(model) {
  const shadcn = model.shadcn.colors ?? {};
  const shadcnNames = new Set(Object.keys(shadcn));
  const tw = model.config.tailwind ?? {};
  const shape = (key) => {
    const token = model.shape.find((s) => s.key === key);
    if (!token) throw new Error(`Unknown shape token "${key}" in export config`);
    return `var(${token.name})`;
  };
  const font = (role) => {
    const f = model.fonts.find((x) => x.role === role);
    return f ? `var(${f.variable}), ${f.fallback}` : null;
  };

  const theme = [];
  theme.push("/* shadcn/ui semantic colors */");
  for (const name of shadcnNames) theme.push(`--color-${name}: var(--${name});`);

  theme.push("", `/* ${model.name} color roles, as bg-*, text-*, border-* utilities */`);
  const skipped = [];
  for (const color of model.coreColors) {
    if (shadcnNames.has(color.key)) skipped.push(color.key);
    else theme.push(`--color-${color.key}: var(${color.name});`);
  }
  for (const tone of model.brand)
    theme.push(`--color-brand-${tone.key}: var(${tone.name});`);

  theme.push("", "/* Fonts */");
  for (const [slot, role] of [["sans", "plain"], ["serif", "brand"], ["mono", "mono"]]) {
    if (font(role)) theme.push(`--font-${slot}: ${font(role)};`);
  }
  if (font("brand")) theme.push(`--font-brand: ${font("brand")};`);

  theme.push("", "/* Radius */");
  for (const [step, key] of Object.entries(tw.radius ?? {}))
    theme.push(`--radius-${step}: ${shape(key)};`);

  theme.push("", "/* Spacing: p-ui-md, gap-ui-lg, … (responsive by window class) */");
  for (const s of model.spacing.ui) theme.push(`--spacing-ui-${s.short}: var(${s.name});`);

  theme.push("", "/* Type sizes: text-headline-large, … Use .type-<role> for the full role. */");
  for (const role of model.typography) {
    if (!role.vars.fontSize) continue;
    theme.push(`--text-${role.id}: var(${role.vars.fontSize});`);
    if (role.vars.lineHeight)
      theme.push(`--text-${role.id}--line-height: var(${role.vars.lineHeight});`);
    if (role.vars.letterSpacing)
      theme.push(`--text-${role.id}--letter-spacing: var(${role.vars.letterSpacing});`);
    if (role.vars.fontWeight)
      theme.push(`--text-${role.id}--font-weight: var(${role.vars.fontWeight});`);
  }

  const shadows = model.elevation.filter((e) => e.key.endsWith("-box-shadow"));
  if (shadows.length) {
    theme.push("", "/* Elevation */");
    for (const e of shadows)
      theme.push(`--shadow-${e.key.replace(/-box-shadow$/, "")}: var(${e.name});`);
  }

  const aliases = Object.entries(shadcn).map(
    ([name, ref]) => `--${name}: ${model.colorVar(ref)};`,
  );
  if (model.shadcn.radius) aliases.push(`--radius: ${shape(model.shadcn.radius)};`);

  const note = skipped.length
    ? `\n * These ${model.name} roles share a name with a shadcn variable, so the\n * utility follows shadcn's meaning. Reach the ${model.name} role with the\n * variable form, e.g. bg-(${model.coreColors.find((c) => c.key === skipped[0]).name}):\n *   ${skipped.join(", ")}\n`
    : "\n";

  return `${banner(model, "Tailwind CSS v4 theme and shadcn/ui variable mapping").trimEnd().replace(/\n \*\/$/, "")}
 *
 * Import after "tailwindcss" and after the tokens. Every value is an alias of
 * a token, so light, dark, and responsive modes need no extra rules here.
 * This replaces the :root / .dark variable blocks a default shadcn/ui setup
 * ships with: delete those so they do not override these.${note} */

@custom-variant dark (&:is(.dark *, [data-theme="dark"] *));

:root,
.dark {
${indent(aliases.join("\n"))}
}

@theme inline {
${indent(theme.join("\n"))}
}
`;
}

const stripBanner = (css) => (css ?? "").replace(/^\/\*[\s\S]*?\*\/\n/, "").trim();

const everythingButFonts = (model) => [
  stripBanner(tokensCss(model)),
  stripBanner(extrasCss(model)),
  stripBanner(baseCss(model)),
  stripBanner(typographyCss(model)),
  ...model.components.map((c) => stripBanner(componentCss(model, c))),
];

/**
 * One self-contained sheet for projects without Tailwind: fonts, tokens, base,
 * type classes, and component styles.
 */
export function stylesCss(model) {
  // @import must precede every other rule, so fonts lead.
  return [fontsCss(model).trim(), ...everythingButFonts(model)].filter(Boolean).join("\n\n") + "\n";
}

/**
 * The same system for Tailwind v4 projects: everything except fonts, plus the
 * theme. Fonts are left out because this sheet has to come *after*
 * "tailwindcss" (so the base layer beats Preflight), where a url() @import is
 * no longer legal. Consumers import fonts.css first instead.
 */
export function tailwindCss(model) {
  return (
    [
      banner(model, 'Tailwind CSS v4 entry. Import after "tailwindcss"; import fonts.css before it.').trim(),
      ...everythingButFonts(model),
      stripBanner(themeCss(model)),
    ]
      .filter(Boolean)
      .join("\n\n") + "\n"
  );
}

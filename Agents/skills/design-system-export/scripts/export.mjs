#!/usr/bin/env node
// Design-system export CLI.
//
//   node export.mjs                 every target
//   node export.mjs lovable v0      only those
//   node export.mjs --list          show targets
//
// Options: --config <file>  kit export config (default: Code/design-export/config.mjs)
//          --out <dir>      output root (default: Export/design-system)
//          --no-archives    skip the .zip / .tgz files
import { existsSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { buildModel } from "./model.mjs";
import { targets } from "./targets/index.mjs";
import { writeTree, zip, npmTarball } from "./lib/util.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const KIT_ROOT = resolve(HERE, "../../../..");

function parseArgs(argv) {
  const options = { targets: [], archives: true };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--list") options.list = true;
    else if (arg === "--no-archives") options.archives = false;
    else if (arg === "--config") options.config = argv[++i];
    else if (arg === "--out") options.out = argv[++i];
    else if (arg === "--help" || arg === "-h") options.help = true;
    else if (arg.startsWith("-")) throw new Error(`Unknown option ${arg}`);
    else options.targets.push(arg);
  }
  return options;
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  const list = () =>
    targets.map((t) => `  ${t.id.padEnd(12)} ${t.summary}`).join("\n");

  if (options.help || options.list) {
    console.log(`Usage: export.mjs [target…] [--config file] [--out dir] [--no-archives]\n\nTargets:\n${list()}`);
    return;
  }

  const unknown = options.targets.filter((id) => !targets.some((t) => t.id === id));
  if (unknown.length)
    throw new Error(`Unknown target: ${unknown.join(", ")}\n\nTargets:\n${list()}`);
  const selected = options.targets.length
    ? targets.filter((t) => options.targets.includes(t.id))
    : targets;

  const configPath = resolve(options.config ?? join(KIT_ROOT, "Code/design-export/config.mjs"));
  if (!existsSync(configPath))
    throw new Error(`No export config at ${configPath}. Pass --config, or create one (see the skill's SKILL.md).`);
  const config = (await import(pathToFileURL(configPath).href)).default;
  if (/^TODO\b/.test(config.name ?? ""))
    throw new Error(
      `${relative(process.cwd(), configPath)} is still the template stub. Fill it in first: see "Setting up a kit" in Agents/skills/design-system-export/SKILL.md.`,
    );
  config.dir = dirname(configPath);
  // Source paths in the config are relative to the code root: the folder above
  // the config's own folder, unless the config says otherwise.
  const codeRoot = resolve(config.dir, config.root ?? "..");
  const outRoot = resolve(options.out ?? join(KIT_ROOT, "Export/design-system"));

  const model = buildModel(config, codeRoot);
  console.log(
    `${model.name} ${model.version}: ${model.colors.length} colors × ${model.colorModes.length} modes, ` +
      `${model.typography.length} type roles, ${model.shape.length} radii, ` +
      `${model.spacing.ui.length + model.spacing.editorial.length} spacing tokens, ` +
      `${model.components.length} components\n`,
  );

  for (const target of selected) {
    const result = target.build(model);
    const dir = join(outRoot, target.id);
    writeTree(dir, result.files);
    for (const archive of options.archives ? (result.archives ?? []) : []) {
      const data = archive.format === "tgz" ? npmTarball(archive.files) : zip(archive.files);
      writeFileSync(join(dir, archive.name), data);
    }
    const count = Object.keys(result.files).length;
    console.log(`${target.title} → ${relative(process.cwd(), dir) || "."}/ (${count} files)`);
    for (const archive of options.archives ? (result.archives ?? []) : [])
      console.log(`  ${archive.name}`);
    for (const step of result.next ?? []) console.log(`  · ${step}`);
    console.log("");
  }

  mkdirSync(outRoot, { recursive: true });
  writeFileSync(
    join(outRoot, "README.md"),
    `# ${model.name} design-system exports\n\nGenerated by \`Agents/skills/design-system-export\`. Do not edit; re-run the export.\n\n| Folder | Platform | Contents |\n| --- | --- | --- |\n${targets.map((t) => `| \`${t.id}/\` | ${t.title} | ${t.summary} |`).join("\n")}\n\nEach folder has its own README with the steps for that platform.\n`,
  );
}

main().catch((error) => {
  console.error(`design-system-export: ${error.message}`);
  process.exit(1);
});
